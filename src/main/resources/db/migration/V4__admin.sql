-- 관리자 기능(LOLog-docs PR #59 spec/admin.md, db.md 인증 V4 초안).
-- 관리자 구분(#21), 계정 정지(#22), 관리자가 탈퇴시키기(#23)에 쓰는 열과 표를 한 번에 만든다.

-- 관리자 구분. 관리자는 보통 회원처럼 가입한 뒤 DB에서 role을 직접 바꿔 정한다.
ALTER TABLE users ADD COLUMN role VARCHAR(10) NOT NULL DEFAULT 'USER';
ALTER TABLE users ADD CONSTRAINT ck_users_role CHECK (role IN ('USER', 'ADMIN'));

-- 계정 정지. 기한(suspended_until)이 지나면 정지가 풀린 것으로 본다.
ALTER TABLE users ADD COLUMN suspended_at TIMESTAMPTZ;
ALTER TABLE users ADD COLUMN suspended_until TIMESTAMPTZ;
ALTER TABLE users ADD COLUMN suspended_reason VARCHAR(200);

-- 정지·해제를 lolog-api에 아직 알리지 못했으면 TRUE. 알릴 때까지 다시 부른다(탈퇴 데이터 삭제와 같은 방식).
ALTER TABLE users ADD COLUMN suspension_notify_pending BOOLEAN NOT NULL DEFAULT FALSE;

CREATE INDEX idx_users_suspension_notify_pending ON users (id) WHERE suspension_notify_pending;

-- 관리자가 탈퇴시킨 계정의 이메일·소셜 계정. 가입·소셜 로그인할 때 걸러 409 ACCOUNT_BANNED
CREATE TABLE banned_identities (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    kind VARCHAR(10) NOT NULL,
    value VARCHAR(254) NOT NULL,
    user_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT banned_identities_pk PRIMARY KEY (id),
    CONSTRAINT uk_banned_identities_kind_value UNIQUE (kind, value),
    CONSTRAINT ck_banned_identities_kind CHECK (kind IN ('EMAIL', 'GOOGLE', 'NAVER'))
);

COMMENT ON COLUMN users.role IS '권한-----USER, ADMIN. 관리자는 DB에서 직접 정함';
COMMENT ON COLUMN users.suspended_at IS '정지 시각-----NULL이면 정지 아님';
COMMENT ON COLUMN users.suspended_until IS '정지 기한-----NULL이고 suspended_at이 있으면 영구 정지. 지나면 정지 아님';
COMMENT ON COLUMN users.suspended_reason IS '정지 이유-----관리자가 적은 1~200자';
COMMENT ON COLUMN users.suspension_notify_pending IS '정지 알림 대기-----TRUE면 lolog-api에 지금 정지 상태를 다시 알릴 대상';
COMMENT ON TABLE banned_identities IS '다시 가입을 막는 이메일·소셜 계정-----관리자가 탈퇴시킨 계정의 것';
COMMENT ON COLUMN banned_identities.kind IS '종류-----EMAIL, GOOGLE, NAVER';
COMMENT ON COLUMN banned_identities.value IS '값-----소문자 이메일 또는 그 회사의 사용자 번호';
COMMENT ON COLUMN banned_identities.user_id IS '탈퇴시킨 회원 ID';
COMMENT ON COLUMN banned_identities.created_at IS '적은 시각';
